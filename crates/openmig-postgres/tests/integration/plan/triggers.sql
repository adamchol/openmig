-- Triggers: CREATE OR REPLACE for definition changes, firing modes, constraint triggers
-- recreated, comments.
-- expect: CREATE OR REPLACE TRIGGER "replaced"
-- expect: DISABLE TRIGGER "toggled"
-- @both
CREATE SCHEMA app;
CREATE TABLE app.t (id integer PRIMARY KEY, a integer, b integer);
CREATE FUNCTION app.f1() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
CREATE FUNCTION app.f2() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
-- @a
CREATE TRIGGER replaced BEFORE INSERT ON app.t FOR EACH ROW EXECUTE FUNCTION app.f1();
CREATE TRIGGER toggled AFTER UPDATE ON app.t FOR EACH STATEMENT EXECUTE FUNCTION app.f1();
CREATE CONSTRAINT TRIGGER ct AFTER INSERT ON app.t DEFERRABLE FOR EACH ROW EXECUTE FUNCTION app.f1();
CREATE TRIGGER gone AFTER DELETE ON app.t FOR EACH ROW EXECUTE FUNCTION app.f2();
-- @b
CREATE TRIGGER replaced BEFORE INSERT OR UPDATE OF a, b ON app.t FOR EACH ROW WHEN (new.a IS NOT NULL) EXECUTE FUNCTION app.f2('x', 'it''s');
CREATE TRIGGER toggled AFTER UPDATE ON app.t FOR EACH STATEMENT EXECUTE FUNCTION app.f1();
ALTER TABLE app.t DISABLE TRIGGER toggled;
CREATE CONSTRAINT TRIGGER ct AFTER INSERT OR DELETE ON app.t DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION app.f1();
CREATE TRIGGER fresh AFTER INSERT ON app.t REFERENCING NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION app.f2();
ALTER TABLE app.t ENABLE ALWAYS TRIGGER fresh;
COMMENT ON TRIGGER replaced ON app.t IS 'replaced';

CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA public;
COMMENT ON EXTENSION citext IS 'case-insensitive text';

CREATE SCHEMA app;
COMMENT ON SCHEMA app IS 'application schema';
GRANT USAGE ON SCHEMA app TO __R__web, __R__worker;
GRANT CREATE ON SCHEMA app TO __R__admin WITH GRANT OPTION;
CREATE SCHEMA audit;

CREATE TYPE app.status AS ENUM ('active', 'disabled', 'deleted');
COMMENT ON TYPE app.status IS 'account status';
REVOKE USAGE ON TYPE app.status FROM PUBLIC;
GRANT USAGE ON TYPE app.status TO __R__web;
CREATE TYPE app.address AS (street text, city text COLLATE "C", zip varchar(10));
CREATE DOMAIN app.email AS public.citext CONSTRAINT email_at CHECK (VALUE ~ '@');
COMMENT ON DOMAIN app.email IS 'email address';
CREATE DOMAIN app.money_amount AS numeric(12,2) NOT NULL DEFAULT 0 CONSTRAINT positive CHECK (VALUE >= 0);
COMMENT ON CONSTRAINT positive ON DOMAIN app.money_amount IS 'no debt';
CREATE DOMAIN app.code AS text COLLATE "C";

CREATE SEQUENCE app.invoice_no AS integer START 1000 INCREMENT 10 MINVALUE 1000 MAXVALUE 999999 CACHE 5 CYCLE;
COMMENT ON SEQUENCE app.invoice_no IS 'invoice numbers';
GRANT USAGE, SELECT ON SEQUENCE app.invoice_no TO __R__worker;

CREATE TABLE app.orgs (
  id bigint GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 5) PRIMARY KEY,
  name text NOT NULL,
  slug text NOT NULL COLLATE "C",
  settings jsonb NOT NULL DEFAULT '{}',
  invoice integer DEFAULT nextval('app.invoice_no'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz,
  CONSTRAINT orgs_slug_key UNIQUE (slug) DEFERRABLE INITIALLY DEFERRED
);
ALTER SEQUENCE app.invoice_no OWNED BY app.orgs.invoice;

CREATE TABLE app.users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id bigint NOT NULL,
  email app.email NOT NULL,
  status app.status NOT NULL DEFAULT 'active',
  tags text[] NOT NULL DEFAULT '{}',
  home app.address,
  balance app.money_amount,
  first_name varchar(100),
  last_name varchar(100),
  full_name text GENERATED ALWAYS AS (coalesce(first_name, '') || ' ' || coalesce(last_name, '')) STORED,
  secret text,
  score double precision,
  n smallint GENERATED BY DEFAULT AS IDENTITY (MINVALUE -5 START WITH -5 MAXVALUE 500 CACHE 3 CYCLE),
  CONSTRAINT users_org_fk FOREIGN KEY (org_id) REFERENCES app.orgs (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT users_score_check CHECK (score >= 0 AND score <= 100) NO INHERIT
);
ALTER TABLE app.users ALTER COLUMN secret SET STORAGE EXTERNAL;
ALTER TABLE app.users ALTER COLUMN secret SET COMPRESSION pglz;
ALTER TABLE app.users ADD CONSTRAINT users_email_org_key UNIQUE (org_id, email) INCLUDE (status) WITH (fillfactor = 90);
ALTER TABLE app.users ADD CONSTRAINT users_status_check CHECK (status <> 'deleted' OR secret IS NULL) NOT VALID;
CREATE INDEX users_lower_email_idx ON app.users (lower(email::text) text_pattern_ops DESC NULLS LAST) WHERE status <> 'deleted';
CREATE INDEX users_name_idx ON app.users (last_name COLLATE "C", first_name DESC NULLS FIRST, (score + 1) NULLS FIRST) INCLUDE (email) WITH (fillfactor = 70);
CREATE INDEX users_tags_idx ON app.users USING gin (tags);
COMMENT ON INDEX app.users_tags_idx IS 'tag search';
ALTER TABLE app.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.users FORCE ROW LEVEL SECURITY;
ALTER TABLE app.users REPLICA IDENTITY USING INDEX users_pkey;
COMMENT ON TABLE app.users IS 'users';
COMMENT ON COLUMN app.users.email IS 'login email';
COMMENT ON CONSTRAINT users_org_fk ON app.users IS 'owning org';

CREATE FUNCTION app.current_org() RETURNS bigint LANGUAGE sql STABLE PARALLEL SAFE
  AS $$ SELECT nullif(current_setting('app.org', true), '')::bigint $$;
CREATE POLICY users_org_isolation ON app.users USING (org_id = app.current_org()) WITH CHECK (org_id = app.current_org());
CREATE POLICY users_admin ON app.users AS RESTRICTIVE FOR DELETE TO __R__worker, __R__admin USING (true);
CREATE POLICY users_select ON app.users FOR SELECT TO PUBLIC, __R__web USING (status <> 'deleted');
CREATE POLICY users_insert ON app.users FOR INSERT TO __R__web WITH CHECK (EXISTS (SELECT 1 FROM app.orgs o WHERE o.id = org_id));
COMMENT ON POLICY users_select ON app.users IS 'hide deleted';

CREATE TABLE app.rooms (
  id integer PRIMARY KEY,
  during tstzrange NOT NULL,
  org_id bigint NOT NULL REFERENCES app.orgs (id) MATCH FULL ON UPDATE RESTRICT ON DELETE SET NULL,
  CONSTRAINT rooms_no_overlap EXCLUDE USING gist (org_id WITH =, during WITH &&) WHERE (id > 0)
);

CREATE TABLE app.statuses (code text PRIMARY KEY, label text NOT NULL, sort integer);
INSERT INTO app.statuses VALUES ('a', 'Active', 1), ('d', 'Disabled', NULL);

CREATE UNLOGGED TABLE app.cache (k text PRIMARY KEY, v bytea) WITH (autovacuum_enabled = false);

CREATE TABLE app.events (id bigint NOT NULL, at timestamptz NOT NULL, payload jsonb) PARTITION BY RANGE (at);
CREATE TABLE app.events_2026 PARTITION OF app.events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE TABLE app.events_default PARTITION OF app.events DEFAULT;
CREATE INDEX events_at_idx ON app.events (at);
ALTER TABLE app.events ADD PRIMARY KEY (id, at);

CREATE TABLE audit.log (id bigserial PRIMARY KEY, at timestamptz NOT NULL DEFAULT now(), actor text);
CREATE TABLE audit.login_log (ip inet) INHERITS (audit.log);
ALTER TABLE audit.log REPLICA IDENTITY FULL;
GRANT SELECT ON audit.log TO __R__worker;

CREATE FUNCTION app.touch() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, app SET work_mem = '64MB'
  AS $$ BEGIN NEW.updated_at := now(); RETURN NEW; END $$;
CREATE FUNCTION app.add(a integer, b integer DEFAULT 1) RETURNS integer LANGUAGE sql IMMUTABLE STRICT LEAKPROOF RETURN a + b;
COMMENT ON FUNCTION app.add(integer, integer) IS 'adds';
REVOKE ALL ON FUNCTION app.add(integer, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION app.add(integer, integer) TO __R__web WITH GRANT OPTION;
CREATE FUNCTION app.add(a numeric, b numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS 'SELECT a + b';
CREATE FUNCTION app.org_users(p_org bigint, VARIADIC p_status app.status[] DEFAULT '{active}') RETURNS TABLE (id uuid, email app.email)
  LANGUAGE sql STABLE ROWS 50 COST 20
  BEGIN ATOMIC SELECT u.id, u.email FROM app.users u WHERE u.org_id = p_org AND u.status = ANY (p_status); END;
CREATE FUNCTION app.split_name(full_name text, OUT first text, OUT last text) LANGUAGE sql IMMUTABLE
  AS $$ SELECT split_part(full_name, ' ', 1), split_part(full_name, ' ', 2) $$;
CREATE FUNCTION app.users_of_org(bigint) RETURNS SETOF app.users LANGUAGE sql AS 'SELECT * FROM app.users WHERE org_id = $1';
CREATE FUNCTION app.debug_dump() RETURNS void LANGUAGE plpgsql AS $$ BEGIN RAISE NOTICE 'x'; END $$;
REVOKE EXECUTE ON FUNCTION app.debug_dump() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION app.debug_dump() TO __R__admin;
CREATE PROCEDURE app.archive(IN p_before timestamptz, INOUT p_count integer DEFAULT 0) LANGUAGE plpgsql
  AS $$ BEGIN p_count := 0; END $$;
GRANT EXECUTE ON PROCEDURE app.archive(timestamptz, integer) TO __R__worker;
COMMENT ON PROCEDURE app.archive(timestamptz, integer) IS 'archives';

CREATE TRIGGER orgs_touch BEFORE UPDATE OF name, slug ON app.orgs FOR EACH ROW WHEN (old.* IS DISTINCT FROM new.*) EXECUTE FUNCTION app.touch();
COMMENT ON TRIGGER orgs_touch ON app.orgs IS 'keeps updated_at';
CREATE FUNCTION app.audit_row() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NULL; END $$;
CREATE TRIGGER users_audit_ins AFTER INSERT ON app.users REFERENCING NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION app.audit_row('insert', 'x''y');
CREATE TRIGGER users_truncate AFTER TRUNCATE ON app.users FOR EACH STATEMENT EXECUTE FUNCTION app.audit_row();
ALTER TABLE app.users DISABLE TRIGGER users_truncate;
CREATE CONSTRAINT TRIGGER rooms_check AFTER INSERT OR UPDATE ON app.rooms DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION app.audit_row();

CREATE VIEW app.active_users AS
  SELECT u.id, u.email, o.name AS org_name FROM app.users u JOIN app.orgs o ON o.id = u.org_id WHERE u.status = 'active';
ALTER VIEW app.active_users SET (security_barrier = true);
COMMENT ON VIEW app.active_users IS 'active users';
COMMENT ON COLUMN app.active_users.org_name IS 'organisation';
GRANT SELECT ON app.active_users TO __R__web;
GRANT SELECT (id) ON app.active_users TO __R__worker;
CREATE VIEW app.org_names AS SELECT id, name FROM app.orgs WITH CASCADED CHECK OPTION;
CREATE VIEW app.user_counts AS SELECT org_id, count(*) AS n FROM app.users GROUP BY org_id;
CREATE FUNCTION app.user_counts_insert() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
CREATE TRIGGER user_counts_insert INSTEAD OF INSERT ON app.user_counts FOR EACH ROW EXECUTE FUNCTION app.user_counts_insert();
CREATE VIEW app.counted AS SELECT c.org_id, c.n, app.add(c.n::integer, 1) AS n1 FROM app.user_counts c;

CREATE MATERIALIZED VIEW app.org_stats AS SELECT org_id, count(*) AS users FROM app.users GROUP BY org_id WITH NO DATA;
CREATE UNIQUE INDEX org_stats_org_idx ON app.org_stats (org_id);
COMMENT ON MATERIALIZED VIEW app.org_stats IS 'stats';

GRANT SELECT, INSERT, UPDATE ON app.users TO __R__web;
GRANT SELECT (id, name), UPDATE (name) ON app.orgs TO __R__worker;
GRANT ALL ON app.orgs TO __R__admin WITH GRANT OPTION;

CREATE FUNCTION app.on_ddl() RETURNS event_trigger LANGUAGE plpgsql AS $$ BEGIN END $$;
CREATE EVENT TRIGGER __R__ddl ON ddl_command_end WHEN TAG IN ('CREATE TABLE', 'ALTER TABLE') EXECUTE FUNCTION app.on_ddl();
ALTER EVENT TRIGGER __R__ddl ENABLE ALWAYS;
COMMENT ON EVENT TRIGGER __R__ddl IS 'ddl hook';
